#!/bin/sh
set -e

# Статика пересобирается на каждом старте: named volume, смонтированный в
# STATIC_ROOT, не обновляется автоматически при выкатке нового образа.
python manage.py collectstatic --noinput

# Миграции здесь НЕ применяются намеренно: автомиграции на старте однажды
# ломают прод в самый неудачный момент. См. README, раздел «Обновление».

exec "$@"
