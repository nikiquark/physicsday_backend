/**
 * Приводит адрес файла к пути от корня домена.
 *
 * Django отдаёт такие пути сам, но ответ мог прийти из кеша, снятого
 * до этой правки, — тогда в нём остался внутренний адрес docker-сети
 * http://backend:8000/media/..., который браузер не разрешит.
 * Здесь он превращается обратно в /media/..., поэтому протухший кеш
 * не ломает картинки.
 *
 * Затрагиваются только пути /media/ и /static/: ссылки партнёров
 * на чужие сайты остаются как есть.
 */
export function toSitePath(url: string | null | undefined): string {
  if (!url) return "";
  const match = url.match(/^https?:\/\/[^/]+(\/(?:media|static)\/.*)$/);
  return match ? match[1] : url;
}
